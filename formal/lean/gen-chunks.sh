#!/usr/bin/env bash
# Generate IntFmt/DecChunksA.lean, DecChunksB.lean, DecChunksC.lean
# from the official intfmt.dec (bash + awk, no Python).
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
dec="${1:-$root/microcode/tinyprintf/intfmt.dec}"
outdir="${2:-$root/formal/lean/IntFmt}"
if [[ ! -f "$dec" ]]; then
  echo "missing $dec" >&2
  exit 1
fi
awk -v outdir="$outdir" '
function lean_str(s,    t) {
  t = s
  gsub(/\\/, "\\\\", t)
  gsub(/"/, "\\\"", t)
  gsub(/\n/, "\\n", t)
  return "\"" t "\""
}
function emit_header(f, name) {
  print "/-" > f
  print "Copyright (C) Ahmad <ahmedparr93@gmail.com>" > f
  print "SPDX-License-Identifier: AGPL-3.0-only" > f
  print "Generated by formal/lean/gen-chunks.sh from intfmt.dec — do not edit." > f
  print "-/" > f
  print "" > f
  print "import IntFmt.DecLoad" > f
  print "" > f
  print "namespace IntFmt" > f
  print "" > f
  print "set_option maxRecDepth 1000000" > f
  print "set_option maxHeartbeats 0" > f
  print "" > f
}
function emit_footer(f) {
  print "" > f
  print "end IntFmt" > f
}
BEGIN {
  n = 0
  nlines = 0
}
{
  line = $0 "\n"
  lines[++nlines] = line
  for (i = 1; i <= NF; i++) {
    v = $i + 0
    if (v < 0) v += 65536
    cell[++n] = v
  }
}
END {
  # 16 cells per full line; last line may be short
  fa = outdir "/DecChunksA.lean"
  fb = outdir "/DecChunksB.lean"
  fc = outdir "/DecChunksC.lean"
  emit_header(fa, "A")
  emit_header(fb, "B")
  emit_header(fc, "C")
  for (k = 0; k < nlines; k++) {
    start = k * 16
    if (start >= n) break
    stop = start + 16
    if (stop > n) stop = n
    if (k < 50) f = fa
    else if (k < 100) f = fb
    else f = fc
    printf("def decLine%03d : String := %s\n", k, lean_str(lines[k+1])) > f
    printf("def decChunk%03d : Array UInt16 := #[", k) > f
    for (i = start + 1; i <= stop; i++) {
      if (i > start + 1) printf(", ") > f
      printf("%d", cell[i]) > f
    }
    printf("]\n") > f
    printf("theorem parse_line%03d : parseDecText decLine%03d = decChunk%03d := rfl\n", k, k, k) > f
    printf("theorem image_chunk%03d : intfmtImage.extract %d %d = decChunk%03d := rfl\n\n", k, start, stop, k) > f
  }
  emit_footer(fa)
  emit_footer(fb)
  emit_footer(fc)
  printf("generated %d lines, %d cells\n", nlines, n) > "/dev/stderr"
}
' "$dec"
