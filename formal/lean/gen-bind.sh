#!/usr/bin/env bash
# Generate IntFmt/DecBindDataA.lean, DecBindDataB.lean, DecBindDataC.lean
# from the official intfmt.dec (bash + awk, no Python).
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
dec="${1:-$root/microcode/tinyprintf/intfmt.dec}"
outdir="${2:-$root/formal/lean/IntFmt}"
if [[ "$outdir" == *.lean ]]; then
  outdir="$(dirname "$outdir")"
fi
if [[ ! -f "$dec" ]]; then
  echo "missing $dec" >&2
  exit 1
fi
awk -v outdir="$outdir" '
BEGIN { nlines = 0 }
{ nlines++; nfields[nlines] = NF }
function pad3(k) { return sprintf("%03d", k) }
function emit_header(f, imp) {
  print "/-" > f
  print "Copyright (C) Ahmad <ahmedparr93@gmail.com>" > f
  print "SPDX-License-Identifier: AGPL-3.0-only" > f
  print "Generated by formal/lean/gen-bind.sh from intfmt.dec — do not edit." > f
  print "-/" > f
  print "" > f
  print "import IntFmt." imp > f
  print "import IntFmt.ParseFacts" > f
  print "" > f
  print "namespace IntFmt" > f
  print "" > f
  print "set_option maxRecDepth 1000000" > f
  print "set_option maxHeartbeats 0" > f
  print "" > f
}
function emit_group(f, name, lo, hi,    i, first, rel, n) {
  n = hi - lo + 1
  printf("def decLines%s : Array String := #[", name) > f
  first = 1
  for (i = lo; i <= hi; i++) {
    if (!first) printf(", ") > f
    first = 0
    printf("decLine%s", pad3(i)) > f
  }
  printf("]\n") > f
  printf("def decChunks%s : Array (Array UInt16) := #[", name) > f
  first = 1
  for (i = lo; i <= hi; i++) {
    if (!first) printf(", ") > f
    first = 0
    printf("decChunk%s", pad3(i)) > f
  }
  printf("]\n\n") > f
  printf("theorem decLines%s_size : decLines%s.size = %d := rfl\n", name, name, n) > f
  printf("theorem decChunks%s_size : decChunks%s.size = %d := rfl\n\n", name, name, n) > f
  for (i = lo; i <= hi; i++) {
    printf("theorem decLine%s_ws : listEndsWS decLine%s.toList := rfl\n", pad3(i), pad3(i)) > f
  }
  printf("\n") > f
  printf("theorem parse_at%s (i : Nat) (h : i < %d) :\n", name, n) > f
  printf("    parseDecText (decLines%s[i]!) = decChunks%s[i]! := by\n", name, name) > f
  for (i = lo; i <= hi; i++) {
    rel = i - lo
    printf("  if hi%s : i = %d then\n", rel, rel) > f
    printf("    subst hi%s; exact parse_line%s\n", rel, pad3(i)) > f
    printf("  else\n") > f
  }
  printf("  omega\n\n") > f
  printf("theorem lines%s_ws (i : Nat) (h : i < %d) :\n", name, n) > f
  printf("    listEndsWS (decLines%s[i]!).toList := by\n", name) > f
  for (i = lo; i <= hi; i++) {
    rel = i - lo
    printf("  if hi%s : i = %d then\n", rel, rel) > f
    printf("    subst hi%s; exact decLine%s_ws\n", rel, pad3(i)) > f
    printf("  else\n") > f
  }
  printf("  omega\n\n") > f
  printf("theorem image_at%s (i : Nat) (h : i < %d) :\n", name, n) > f
  printf("    intfmtImage.extract (lineStart%s i) (lineStop%s i) = decChunks%s[i]! := by\n", name, name, name) > f
  for (i = lo; i <= hi; i++) {
    rel = i - lo
    printf("  if hi%s : i = %d then\n", rel, rel) > f
    printf("    subst hi%s; exact image_chunk%s\n", rel, pad3(i)) > f
    printf("  else\n") > f
  }
  printf("  omega\n") > f
}
END {
  fa = outdir "/DecBindDataA.lean"
  fb = outdir "/DecBindDataB.lean"
  fc = outdir "/DecBindDataC.lean"
  emit_header(fa, "DecChunksA")
  print "def lineStartA (i : Nat) : Nat := 16 * i" > fa
  print "def lineStopA (i : Nat) : Nat := 16 * i + 16" > fa
  print "" > fa
  emit_group(fa, "A", 0, 49)
  print "" > fa
  print "end IntFmt" > fa

  emit_header(fb, "DecChunksB")
  print "def lineStartB (i : Nat) : Nat := 800 + 16 * i" > fb
  print "def lineStopB (i : Nat) : Nat := 800 + 16 * i + 16" > fb
  print "" > fb
  emit_group(fb, "B", 50, 99)
  print "" > fb
  print "end IntFmt" > fb

  emit_header(fc, "DecChunksC")
  print "def lineStartC (i : Nat) : Nat := 1600 + 16 * i" > fc
  print "def lineStopC (i : Nat) : Nat := if i = 45 then 2323 else 1600 + 16 * i + 16" > fc
  print "" > fc
  emit_group(fc, "C", 100, nlines - 1)
  print "" > fc
  print "end IntFmt" > fc
  printf("generated DecBindDataA/B/C for %d lines\n", nlines) > "/dev/stderr"
}
' "$dec"
